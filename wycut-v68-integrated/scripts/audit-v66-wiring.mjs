import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const pricing = JSON.parse(await readFile(new URL('../config/credit-pricing.json', import.meta.url), 'utf8'));
const charge = await readFile(new URL('../app/api/editor/export/charge/route.ts', import.meta.url), 'utf8');
const editor = await readFile(new URL('../components/dashboard-workspace.tsx', import.meta.url), 'utf8');
const timeline = await readFile(new URL('../lib/editor/timeline-model.ts', import.meta.url), 'utf8');
assert.equal(pricing.editorAssets.exportCostsCredits['1080p'], 3, '1080p export price must be configured');
assert.equal(pricing.editorAssets.exportCostsCredits['2K'], 5, '2K export price must be configured');
assert.equal(pricing.editorAssets.exportCostsCredits.watermarkRemoval, 2, 'watermark removal price must be configured');
assert.match(charge, /verifyGoogleIdentity/, 'export charge requires verified account identity');
assert.match(charge, /isAllowedApiOrigin/, 'export charge validates request origin');
assert.match(charge, /runTransaction/, 'export credit settlement must be transactional');
assert.match(charge, /specHash/, 'idempotency key must reject option changes');
assert.match(charge, /watermarkRemoved/, 'watermark removal is priced server-side');
assert.match(editor, /Credits are charged only after rendering succeeds/, 'client discloses charge timing before export');
assert.match(editor, /watermarkRemoved: !showWatermark/, 'client sends watermark removal selection');
assert.match(editor, /\/api\/editor\/export\/charge/, 'export settlement is connected to UI');
assert.match(timeline, /export function copyTimelineClips/, 'timeline copy is implemented');
assert.match(timeline, /export function pasteTimelineClips/, 'timeline paste is implemented');
assert.match(timeline, /Ripple deletion is timeline-wide/, 'ripple deletion propagates across lanes');
assert.doesNotMatch(charge, /Google Play Billing/i, 'current payment stack must not switch to Google Play Billing');
console.log('v66 wiring audit passed: Flutterwave v4 purchase architecture retained; export pricing/settlement, idempotency, watermark policy, and timeline copy/paste/ripple are wired.');
