import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => fs.readFileSync(p,'utf8');
const config = JSON.parse(read('config/credit-pricing.json'));
const pricing = read('lib/billing/pricing.ts');
const transcribe = read('app/api/transcribe/route.ts');
const estimate = read('app/api/transcribe/estimate/route.ts');
const client = read('lib/transcribe/client.ts');
const background = read('app/api/background-removal/route.ts');
assert.equal(config.usdNgnRate,1400);
assert.equal(config.packs.find(p=>p.id==='starter').usd,1);
assert.equal(config.rates.transcribeSecondsPerCredit,80);
assert.equal(config.rates.transcribeWhisperSecondsPerCredit,18);
assert.ok(config.costModelUsd.minimumMarginAtCheapestPack >= 0.65);
assert.match(pricing,/provider: TranscriptionProvider/);
assert.match(transcribe,/transcribeCredits\(duration, selectedProvider\)/);
assert.match(transcribe,/estimatedProviderCostUsd/);
assert.match(transcribe,/providerCostEstimateType: 'conservative_model_estimate'/);
assert.match(estimate,/transcribeCredits\(seconds, provider\)/);
assert.match(client,/api\/transcribe\/estimate/);
assert.match(background,/BACKGROUND_SEGMENTATION_NOT_IMPLEMENTED/);
assert.match(background,/creditsCharged: 0/);
console.log('WyCut v58 provider-aware pricing, preflight estimate, and no-fake-background-removal audit passed. This is a static audit, not a production build or live-provider test.');
