import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const ui = read('components/dashboard-workspace.tsx');
const renderer = read('lib/ffmpeg/edit-export.ts');
assert.match(ui, /image\/png,image\/jpeg,image\/webp/);
assert.match(ui, /Export as image \(PNG\)/);
assert.match(ui, /Export as video \(5-second MP4\)/);
assert.match(ui, /kind === 'video' \? await renderEditPlan\(video/);
assert.match(ui, /Final_Image\.png/);
assert.match(ui, /if \(driveToken\) await exportDrive\(finalVideo\)/);
assert.match(renderer, /const stillImage = input\.type\.startsWith\('image\/'\)/);
assert.match(renderer, /'-loop', '1', '-framerate', '30', '-t', '5', '-i', inputName/);
assert.match(renderer, /stillImage \? \['-an'\]/);
console.log('WyCut v53 image-only export audit passed: image/video choice, PNG output, five-second MP4 loop, Drive MIME and silent still-image encoding.');
