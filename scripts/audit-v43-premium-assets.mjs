import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = process.cwd();
const config = JSON.parse(fs.readFileSync(path.join(root, 'config/credit-pricing.json'), 'utf8'));
const route = fs.readFileSync(path.join(root, 'app/api/editor/assets/unlock/route.ts'), 'utf8');
const editor = fs.readFileSync(path.join(root, 'components/advanced-editor-tools.tsx'), 'utf8');
const helper = fs.readFileSync(path.join(root, 'lib/editor/unlock-premium-asset.ts'), 'utf8');
const sounds = fs.readFileSync(path.join(root, 'components/sound-library.tsx'), 'utf8');
for (const category of ['font','animation','sound','filter','effect','transition','sticker']) assert.ok(config.editorAssets.premiumUnlockCosts[category] > 0, `missing positive price for ${category}`);
for (const category of ['fonts','animations','sounds','filters','effects','transitions','stickers']) assert.ok(Array.isArray(config.editorAssets.premium[category]), `missing premium allowlist ${category}`);
assert.match(route, /verifyGoogleIdentity/);
assert.match(route, /runTransaction/);
assert.match(route, /wycut_editor_asset_unlocks/);
assert.match(route, /wycut_credit_ledger/);
assert.match(route, /InsufficientCreditsError/);
assert.match(editor, /unlockPremiumEditorAsset/);
for (const category of ['font','animation','filter','effect','transition']) assert.ok(editor.includes(`'${category}'`), `editor is not wired for ${category}`);
assert.match(helper, /api\/editor\/assets\/unlock/);
assert.match(sounds, /unlockPremiumEditorAsset\('sound'/);
assert.match(sounds, /premiumSoundCategories/);
console.log('v43 premium asset audit passed: server allowlist, positive prices, atomic one-time unlock, ledger and editor wiring are present.');
